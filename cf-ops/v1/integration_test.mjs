import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import "./cf-ops-preload.mjs";
import assert from "node:assert";
const server = new McpServer({ name: "t", version: "1" });
const [a, b] = InMemoryTransport.createLinkedPair();
await server.connect(a);
const client = new Client({ name: "c", version: "1" });
await client.connect(b);
const tools = (await client.listTools()).tools.map(t => t.name);
console.log("TOOLS", tools.length);
const c = async (name, args) => (await client.callTool({ name, arguments: args })).structuredContent;
const D = "/tmp/cfops-it"; 
let r;
r = await c("server_status", {}); assert.equal(r.state, "ACHIEVED", JSON.stringify(r)); console.log("status user", r.result.user);
r = await c("server_exec", { command: "echo hi; echo err >&2; exit 3" }); assert.equal(r.result.exit_code, 3); assert.equal(r.result.stdout, "hi\n");
r = await c("server_exec", { command: "sleep 30 & sleep 30", timeout_s: 2 }); assert.equal(r.result.exit_code, 124); console.log("timeout ms", r.result.duration_ms);
r = await c("server_exec", { command: `rm -rf ${D}; mkdir -p ${D}` });
r = await c("server_file_write", { path: D + "/a.txt", content: "hello world\n" }); assert.equal(r.state, "ACHIEVED", JSON.stringify(r));
r = await c("server_file_write", { path: D + "/a.txt", content: "x" }); assert.equal(r.state, "FAILED"); console.log("create-exists", r.error.code);
r = await c("server_file_edit", { path: D + "/a.txt", old_text: "world", new_text: "CF" }); assert.equal(r.state, "ACHIEVED");
r = await c("server_file_read", { path: D + "/a.txt" }); assert.equal(r.result.content, "hello CF\n");
r = await c("server_file_copy", { src: D + "/a.txt", dst: D + "/b.txt" }); assert.equal(r.state, "ACHIEVED");
r = await c("server_file_move", { src: D + "/b.txt", dst: D + "/c.txt" }); assert.equal(r.state, "ACHIEVED");
r = await c("server_file_search", { path: D, content_regex: "CF" }); assert.equal(r.result.matches.length, 2);
r = await c("server_file_list", { path: D }); assert.equal(r.result.entries.length, 2);
r = await c("server_file_stat", { path: D + "/c.txt" }); assert.equal(r.result.size_bytes, 9);
r = await c("server_file_delete", { path: D + "/c.txt", confirm: true }); assert.equal(r.state, "ACHIEVED");
const data = Buffer.from("upload-data-123");
r = await c("server_file_upload", { action: "start", path: D + "/u.bin", size_bytes: data.length }); const id = r.result.upload_id;
r = await c("server_file_upload", { action: "chunk", upload_id: id, offset: 0, content_base64: data.toString("base64") }); assert.equal(r.result.complete, true);
r = await c("server_file_upload", { action: "finish", upload_id: id }); assert.equal(r.state, "ACHIEVED", JSON.stringify(r));
r = await c("server_file_fetch", { url_or_cf_download_path: "https://raw.githubusercontent.com/homayounisaghar/cf-exec-plane/main/README.md", dest_path: D + "/readme.md" }); console.log("fetch", r.state, r.result?.size_bytes ?? JSON.stringify(r.error));
r = await c("server_exec", { command: "for i in 1 2 3; do echo line$i; sleep 1; done", background: true, label: "t" }); const job = r.result.job_id; assert.ok(job);
await new Promise(s => setTimeout(s, 4500));
r = await c("server_job_status", { job_id: job }); assert.equal(r.result.exit_code, 0, JSON.stringify(r));
r = await c("server_job_output", { job_id: job }); assert.equal(r.result.stdout, "line1\nline2\nline3\n");
r = await c("server_exec", { command: "sleep 100", background: true }); const j2 = r.result.job_id;
await new Promise(s => setTimeout(s, 1000));
r = await c("server_job_kill", { job_id: j2 }); assert.equal(r.state, "ACHIEVED", JSON.stringify(r));
await new Promise(s => setTimeout(s, 1500));
r = await c("server_job_status", { job_id: j2 }); assert.equal(r.result.running, false, JSON.stringify(r)); console.log("killed exit", r.result.exit_code);
r = await c("server_job_list", {}); assert.ok(r.result.jobs.length >= 2);
r = await c("github_auth_status", {}); console.log("gh", JSON.stringify(r.result));
r = await c("github_repo_list", {}); console.log("gh repo", r.error?.code);
console.log("ALL_PASS");
process.exit(0);
